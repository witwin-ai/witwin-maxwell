"""Independent material stability and final-coefficient time-step checks."""
import math

import numpy as np
import pytest
import torch

import witwin.maxwell as mw


def _simulation(material, *, dt=None, max_electric_field=None, boundary=None):
    scene = mw.Scene(domain=mw.Domain(bounds=((-0.2, 0.2),) * 3),
        grid=mw.GridSpec.uniform(0.1), boundary=boundary or mw.BoundarySpec.periodic(), device="cuda")
    scene.add_structure(mw.Structure(geometry=mw.Box(position=(0., 0., 0.), size=(1.,) * 3), material=material))
    scene.add_source(mw.PointDipole(position=(0., 0., 0.), polarization="Ez", source_time=mw.CW(frequency=0.7e9)))
    return mw.Simulation.fdtd(scene, frequency=0.7e9,
        run_time=mw.TimeConfig(time_steps=200, dt=dt, max_electric_field=max_electric_field), cuda_graph=False)


@pytest.mark.parametrize("dt", [0., -1., float("inf"), float("nan")])
def test_explicit_time_step_must_be_positive_finite(dt):
    with pytest.raises(ValueError, match="positive and finite"):
        mw.TimeConfig(dt=dt)


@pytest.mark.skipif(not torch.cuda.is_available(), reason="requires CUDA")
@pytest.mark.parametrize("eps,mu", [(0.25, 1.), (1., 0.25), (0.4, 0.6)])
def test_material_wave_speed_limits_automatic_and_explicit_step(eps, mu):
    material = mw.Material(eps_r=eps, mu_r=mu)
    solver = _simulation(material).prepare().solver
    exact_limit = math.sqrt(eps * mu) * 0.1 / (solver.c * math.sqrt(3))
    assert solver.dt <= 0.9 * exact_limit * (1 + 1e-6)
    explicit = _simulation(material, dt=0.5 * solver.dt).prepare().solver
    assert explicit.dt == 0.5 * solver.dt
    with pytest.raises(ValueError, match="safe FDTD time-step limit"):
        _simulation(material, dt=2 * exact_limit).prepare()


def _lorentz_matrix(entry, dt, background):
    decay = entry["decay"]
    restoring = entry["restoring"]
    drive = float(entry["drive"].max())
    # State order E, P, J; generated by the actual old-field ADE recurrence.
    matrix = np.empty((3, 3))
    for column in range(3):
        electric, polarization, current = np.eye(3)[:, column]
        next_current = decay * current - restoring * polarization + drive * electric
        next_polarization = polarization + dt * next_current
        matrix[:, column] = (electric - dt * next_current / background, next_polarization, next_current)
    return matrix


@pytest.mark.skipif(not torch.cuda.is_available(), reason="requires CUDA")
@pytest.mark.parametrize("magnetic", [False, True])
@pytest.mark.parametrize("strength", [10., 1000.])
def test_strong_lorentz_uses_coupled_frequency_and_final_dt(magnetic, strength):
    pole = mw.LorentzPole(delta_eps=strength, resonance_frequency=1e9, gamma=0.)
    material = mw.Material(mu_lorentz_poles=(pole,)) if magnetic else mw.Material(lorentz_poles=(pole,))
    solver = _simulation(material).prepare().solver
    component = "Hx" if magnetic else "Ex"
    templates = solver._magnetic_dispersive_templates if magnetic else solver._dispersive_templates
    entry = templates[component]["lorentz"][0]
    background = solver.mu0 if magnetic else solver.eps0
    matrix = _lorentz_matrix(entry, solver.dt, background)
    assert max(abs(np.linalg.eigvals(matrix))) <= 1 + 2e-6
    assert entry["restoring"] == pytest.approx((2 * math.pi * 1e9)**2 * solver.dt, rel=1e-12)
    assert solver.dt * 2 * math.pi * 1e9 * math.sqrt(1 + strength) < 2

    from witwin.maxwell.fdtd.runtime.stepping import _field_update_block
    getattr(solver, component).fill_(1.)
    reference = np.array([1., 0., 0.])
    for index in range(1000):
        _field_update_block(solver, index * solver.dt)
        solver._apply_dispersive_corrections()
        reference = matrix @ reference
        if index % 50 == 0:
            assert float((getattr(solver, component) - reference[0]).abs().max()) < 2e-4
    assert torch.isfinite(getattr(solver, component)).all()


@pytest.mark.skipif(not torch.cuda.is_available(), reason="requires CUDA")
def test_density_bounds_keep_time_step_fixed_across_perturbations():
    scene = mw.Scene(domain=mw.Domain(bounds=((-0.2, 0.2),) * 3),
        grid=mw.GridSpec.uniform(0.1), boundary=mw.BoundarySpec.pec(), device="cuda")
    values = []
    for density in (0.1, 0.9):
        variant = scene.clone()
        variant.add_material_region(mw.MaterialRegion(name="design",
            geometry=mw.Box(position=(0., 0., 0.), size=(0.4,) * 3),
            density=torch.full((2, 2, 2), density, device="cuda"), eps_bounds=(0.25, 4.)))
        values.append(mw.Simulation.fdtd(variant, frequency=0.7e9).prepare().solver.dt)
    assert values[0] == values[1]


@pytest.mark.skipif(not torch.cuda.is_available(), reason="requires CUDA")
def test_electric_magnetic_lorentz_joint_fourier_bound():
    electric = mw.LorentzPole(delta_eps=1000., resonance_frequency=1e9, gamma=0.)
    magnetic = mw.LorentzPole(delta_eps=400., resonance_frequency=1.7e9, gamma=0.)
    solver = _simulation(mw.Material(lorentz_poles=(electric,), mu_lorentz_poles=(magnetic,))).prepare().solver
    # Test the stability boundary, independently of the finer response-resolution step.
    dt = 0.9 * solver._time_step_metadata["stability_limit"]
    for fraction in (0., 0.2, 0.6, 1.):
        kdt = fraction * solver._time_step_metadata["curl_rate_bound"] * dt
        columns = []
        for electric_field, magnetic_field, ep, ej, mp, mj in np.eye(6):
            mj += (2 * math.pi * magnetic.resonance_frequency * dt)**2 * (magnetic.delta_eps * magnetic_field - mp)
            mp += mj
            magnetic_field -= kdt * electric_field + mj
            ej += (2 * math.pi * electric.resonance_frequency * dt)**2 * (electric.delta_eps * electric_field - ep)
            ep += ej
            electric_field += kdt * magnetic_field - ej
            columns.append((electric_field, magnetic_field, ep, ej, mp, mj))
        assert max(abs(np.linalg.eigvals(np.asarray(columns).T))) < 1 + 1e-9


@pytest.mark.skipif(not torch.cuda.is_available(), reason="requires CUDA")
def test_strong_debye_feedback_is_stable():
    solver = _simulation(mw.Material.debye(eps_inf=1., delta_eps=1000., tau=1e-9)).prepare().solver
    entry = solver._dispersive_templates["Ex"]["debye"][0]
    eigenvalue = entry["decay"] - float(entry["drive"].max()) / solver.eps0
    assert abs(eigenvalue) < 1


@pytest.mark.skipif(not torch.cuda.is_available(), reason="requires CUDA")
def test_full_tensor_lower_eigenvalue_and_modulation_minimum():
    matrix = ((0.3, 0.2, 0.), (0.2, 0.3, 0.), (0., 0., 1.))
    anisotropic = _simulation(mw.Material(epsilon_tensor=mw.Tensor3x3(matrix))).prepare().solver
    assert anisotropic._time_step_metadata["epsilon_lower_bound"] == pytest.approx(0.1, rel=1e-5)
    modulated = _simulation(mw.Material(eps_r=0.4,
        modulation=mw.ModulationSpec(frequency=0.1e9, amplitude=0.25))).prepare().solver
    assert modulated._time_step_metadata["epsilon_lower_bound"] == pytest.approx(0.3, rel=1e-5)


@pytest.mark.skipif(not torch.cuda.is_available(), reason="requires CUDA")
def test_negative_nonlinear_increment_envelope_is_checked():
    from witwin.maxwell.fdtd.runtime.timestep import validate_nonlinear_field_envelope

    material = mw.Material(eps_r=4., kerr_chi3=-1e-4)
    solver = _simulation(material, max_electric_field=80.).prepare().solver
    assert solver._time_step_metadata["epsilon_lower_bound"] == pytest.approx(2.08, rel=1e-5)
    solver.Ex.fill_(100.)
    solver._update_nonlinear_electric_coefficients()
    with pytest.raises(RuntimeError, match="stability envelope"):
        validate_nonlinear_field_envelope(solver)
    with pytest.raises(ValueError, match="positive finite high-frequency"):
        _simulation(material, max_electric_field=200.).prepare()


@pytest.mark.skipif(not torch.cuda.is_available(), reason="requires CUDA")
def test_trainable_simulation_freezes_step_and_rejects_unsafe_update():
    perturbation = torch.zeros((2, 2, 2), device="cuda", requires_grad=True)
    simulation = _simulation(mw.PerturbationMedium(mw.Material(eps_r=0.04),
        perturbation=perturbation, eps_sensitivity=1.), boundary=mw.BoundarySpec.pec())
    initial = simulation.prepare().solver.dt
    with torch.no_grad():
        perturbation.fill_(0.001)
    assert simulation.prepare().solver.dt == initial
    with torch.no_grad():
        perturbation.fill_(-0.02)
    with pytest.raises(ValueError, match="safe FDTD time-step limit"):
        simulation.prepare()
