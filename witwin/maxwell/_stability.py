"""Stability markers of the public API.

A public object is stable unless it is marked experimental. ``experimental(feature)``
marks a class or function: it records the object under ``feature`` (``stability()`` and
``feature_of()`` read the record), sets ``__stability__ = "experimental"`` on it, and the
first time code outside witwin-maxwell constructs the class or calls the function, one
``ExperimentalWarning`` per object and process is emitted. Library-internal construction
(results, reports, defaults) stays silent, so a stable workflow never warns. A class
without a constructor of its own (an abstract base, a protocol, a named tuple, an
exception) is recorded only. A protocol gets no ``__stability__`` attribute: every class
attribute of a runtime-checkable protocol would become a required member.

Objects are marked where they are defined, except in files that a provenance gate pins byte
for byte (``rational.py``, pinned by the consumer-metadata bridge): those are marked in the
namespace façade that publishes them.

An object owned by another package (``witwin.core.ExtrudedPolygon``, re-exported by
``mw.geometry``) is marked with ``experimental_external(feature)``: it is only recorded, so
``stability()``, ``feature_of()``, ``docs/reference/public-api.csv`` and FEATURE_LIST report it
as experimental, but the object itself is not modified (no ``__init__`` wrapper, no
``__stability__`` attribute). Rebinding another package's objects would mutate them for every
importer (the consumer-metadata bridge refuses it). An externally owned class therefore emits no
``ExperimentalWarning``.

The check runs on construction and call, never inside a solver: mark constructors and
user entry points, not kernels. Once an object has warned, its wrapper is one flag test.

``docs/reference/public-api.csv`` lists every public object with its stability; it is
generated by ``scripts/dev/public_api.py`` and checked against these markers by
``tests/api/public/test_public_api_stability.py``.
"""
from __future__ import annotations

import functools
import inspect
import sys
import warnings

from .errors import ExperimentalWarning

STABLE = "stable"
EXPERIMENTAL = "experimental"

# Experimental feature key -> what it covers (the warning text and the FEATURE_LIST
# "API Stability" table).
FEATURES = {
    "antenna": "antenna arrays, beams, MIMO and array scene gradients",
    "batch": "the Batch execution tier",
    "breakdown": "dynamic dielectric breakdown",
    "circuits": "circuit (MNA) co-simulation",
    "coordinates": "bent coordinate charts",
    "electrostatics": "electrostatics and capacitance extraction",
    "esd": "ESD stress analysis",
    "fdfd": "the FDFD solver",
    "geometry": "the general extruded-polygon geometry primitive",
    "invdes": "the inverse-design toolkit",
    "mom": "the MoM surface-integral solver",
    "mom_layered": "layered-media MoM networks",
    "monitors": "diffraction-order and dipole-emission monitors",
    "networks": "embedded networks, Touchstone blocks and low-frequency network smoothing",
    "path_integrals": "custom voltage and current path integrals",
    "pcb": "printed-circuit conductors",
    "rational": "rational fitting and state-space networks",
    "rf_ports": "wave, terminal and coaxial ports and port sweeps",
    "roughness": "conductor surface roughness",
    "thin_wire": "thin wires",
}

_PACKAGE = __name__.rpartition(".")[0]
# Modules that construct an object on behalf of their caller (``dataclasses.replace``,
# ``copy.copy``): the caller one frame further out decides.
_TRANSPARENT = frozenset({"dataclasses", "copy"})


_MARKED: dict[object, str] = {}  # marked object -> feature key


def feature_of(obj) -> str | None:
    """The feature key ``obj`` is experimental under, or ``None``.

    The object's own marker counts, not an inherited one: a stable subclass of an
    experimental class is stable.
    """
    try:
        return _MARKED.get(getattr(obj, "__func__", obj))
    except TypeError:  # an unhashable constant
        return None


def stability(obj) -> str:
    """``"experimental"`` for a marked object, ``"stable"`` otherwise."""
    return EXPERIMENTAL if feature_of(obj) else STABLE


def experimental(feature: str):
    """Mark a public class or function as experimental under ``feature`` (a ``FEATURES`` key)."""
    description = FEATURES[feature]

    def mark(obj):
        message = (f"{obj.__qualname__} is experimental ({description}); its API and results may "
                   "change in any release. See FEATURE_LIST.md, API Stability.")
        if isinstance(obj, type):
            if _constructible(obj):
                obj.__init__ = _warn_once(obj.__init__, message)
        else:
            obj = _warn_once(obj, message)
        _MARKED[obj] = feature
        if not getattr(obj, "_is_protocol", False):
            obj.__stability__ = EXPERIMENTAL
        return obj

    return mark


def experimental_external(feature: str):
    """Record an object owned by another package as experimental under ``feature`` without modifying it."""
    FEATURES[feature]

    def mark(obj):
        _MARKED[obj] = feature
        return obj

    return mark


def _constructible(cls: type) -> bool:
    return not (issubclass(cls, BaseException) or getattr(cls, "_is_protocol", False)
                or inspect.isabstract(cls) or cls.__init__ is object.__init__)


def _warn_once(function, message: str):
    warned = False

    @functools.wraps(function)
    def wrapper(*args, **kwargs):
        nonlocal warned
        if not warned and _called_from_outside():
            warned = True
            warnings.warn(message, ExperimentalWarning, stacklevel=2)
        return function(*args, **kwargs)

    return wrapper


def _called_from_outside() -> bool:
    """Whether the caller of the marked object is code outside witwin-maxwell."""
    frame = sys._getframe(2)  # the caller of the wrapper
    while frame is not None and frame.f_globals.get("__name__") in _TRANSPARENT:
        frame = frame.f_back
    name = "" if frame is None else frame.f_globals.get("__name__", "")
    return not (name == _PACKAGE or name.startswith(_PACKAGE + "."))
