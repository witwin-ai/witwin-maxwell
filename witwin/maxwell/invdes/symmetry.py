"""Symmetry projectors on the design-parameter grid.

A symmetry is a set of generators (axis mirrors, 2- or 4-fold rotations and
diagonal mirrors about the grid centre). :func:`symmetrize` closes the generators
into their finite point group and averages the field over every group element.
The group average is an orthogonal projector: idempotent, self-adjoint (the
gradient is symmetrized by the same average) and the identity on fields that
already have the symmetry, for any combination of generators.

Apply it to the raw parameters before filtering; the density filters use
flip-equivariant kernels and padding, so filtered and projected densities keep
the imposed symmetry (rotations and diagonal mirrors additionally need equal
spacing along the affected axes for the kernel to be invariant).
"""

from __future__ import annotations

from collections.abc import Sequence

import torch

# A group element is a signed axis permutation ``g`` with ``(g r)_j = s_j r_{q_j}``
# stored as ``((q_0, s_0), ..., (q_{n-1}, s_{n-1}))`` on centred cell coordinates.
_Element = tuple[tuple[int, int], ...]


def _identity(ndim: int) -> _Element:
    return tuple((axis, 1) for axis in range(ndim))


def _compose(a: _Element, b: _Element) -> _Element:
    # (a b r)_j = s^a_j (b r)_{q^a_j} = s^a_j s^b_{q^a_j} r_{q^b_{q^a_j}}
    return tuple((b[q][0], s * b[q][1]) for q, s in a)


def _axis(dim: int, ndim: int) -> int:
    if not -ndim <= int(dim) < ndim:
        raise ValueError(f"symmetry axis {dim} is out of range for a {ndim}D grid.")
    return int(dim) % ndim


def _plane(dims, ndim: int) -> tuple[int, int]:
    dims = tuple(dims)
    if len(dims) != 2:
        raise ValueError("a symmetry plane must name exactly two axes.")
    a, b = _axis(dims[0], ndim), _axis(dims[1], ndim)
    if a == b:
        raise ValueError("a symmetry plane must name two distinct axes.")
    return a, b


def _generators(ndim, mirror, rotation, rotation_dims, diagonal) -> list[_Element]:
    generators = []
    for dim in mirror:
        axis = _axis(dim, ndim)
        generators.append(tuple((j, -1 if j == axis else 1) for j in range(ndim)))
    if rotation is not None:
        order = int(rotation)
        if order not in (2, 4):
            raise ValueError("rotational symmetry order must be 2 or 4 on a Cartesian grid.")
        a, b = _plane(rotation_dims, ndim)
        element = list(_identity(ndim))
        if order == 2:
            element[a], element[b] = (a, -1), (b, -1)
        else:
            element[a], element[b] = (b, -1), (a, 1)
        generators.append(tuple(element))
    if diagonal is not None:
        a, b = _plane(diagonal, ndim)
        element = list(_identity(ndim))
        element[a], element[b] = (b, 1), (a, 1)
        generators.append(tuple(element))
    return generators


def _closure(generators: list[_Element], ndim: int) -> list[_Element]:
    group = {_identity(ndim)}
    frontier = list(group)
    while frontier:
        new = []
        for element in frontier:
            for generator in generators:
                product = _compose(generator, element)
                if product not in group:
                    group.add(product)
                    new.append(product)
        frontier = new
    return sorted(group)


def _apply(x: torch.Tensor, element: _Element) -> torch.Tensor:
    # y(r) = x(g r): x axis j is read from y axis q_j, reversed where s_j < 0.
    dims = [0] * x.ndim
    for j, (q, _) in enumerate(element):
        dims[q] = j
    y = x.permute(dims)
    flips = [q for q, s in element if s < 0]
    return y.flip(flips) if flips else y


def symmetrize(
    x: torch.Tensor,
    *,
    mirror: Sequence[int] = (),
    rotation: int | None = None,
    rotation_dims: Sequence[int] = (0, 1),
    diagonal: Sequence[int] | None = None,
) -> torch.Tensor:
    """Project ``x`` onto the point group generated by the given symmetries.

    ``mirror``: axes mirrored across the grid centre. ``rotation``: ``2`` or
    ``4``-fold rotation in the ``rotation_dims`` plane. ``diagonal``: an axis
    pair ``(a, b)`` mirrored across the main diagonal (``a <-> b`` swap).
    Rotations by 90 degrees and diagonal mirrors require equal lengths along
    both plane axes.
    """
    generators = _generators(x.ndim, tuple(mirror), rotation, rotation_dims, diagonal)
    if not generators:
        return x
    group = _closure(generators, x.ndim)
    for element in group:
        for j, (q, _) in enumerate(element):
            if x.shape[j] != x.shape[q]:
                raise ValueError(
                    f"symmetry maps axis {j} onto axis {q}, which requires equal grid lengths "
                    f"(got {x.shape[j]} and {x.shape[q]})."
                )
    return sum(_apply(x, element) for element in group) / len(group)


def mirror_symmetrize(x: torch.Tensor, dims: int | Sequence[int]) -> torch.Tensor:
    """Mirror symmetry across the centre of each axis in ``dims``."""
    return symmetrize(x, mirror=(dims,) if isinstance(dims, int) else tuple(dims))


def rotational_symmetrize(x: torch.Tensor, order: int, dims: Sequence[int] = (0, 1)) -> torch.Tensor:
    """``order``-fold (2 or 4) rotational symmetry in the ``dims`` plane."""
    return symmetrize(x, rotation=order, rotation_dims=dims)


def diagonal_symmetrize(x: torch.Tensor, dims: Sequence[int] = (0, 1)) -> torch.Tensor:
    """Mirror symmetry across the diagonal of the ``dims`` plane (transpose)."""
    return symmetrize(x, diagonal=dims)
