"""Generate the documentation capability tables from the capability registry.

    python scripts/dev/capability_tables.py          # check: print a diff and exit 1 when a table is stale
    python scripts/dev/capability_tables.py --write  # regenerate every table in place

Two reference pages are generated whole: ``docs/reference/capability-registry.md``
(every row of every method table) and ``docs/reference/scene-field-consumption.md``
(the field-consumption manifest). Hand-written pages carry generated blocks
between ``<!-- capability-table: NAME -->`` and ``<!-- /capability-table: NAME -->``
markers: the FEATURE_LIST FDFD, Known Limitations, MoM and electrostatics
sections, the gradient capability matrix and the guard census.
"""
from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from witwin.maxwell.capability import FEATURE_KEYS, METHODS, SCENE_KEYS, Support, capabilities  # noqa: E402
from witwin.maxwell.capability.fields import ENTRIES, consumption, row  # noqa: E402

GENERATED = "<!-- Generated by scripts/dev/capability_tables.py; do not edit. -->"
LABEL = {Support.SUPPORTED: "yes", Support.UNSUPPORTED: "no", Support.INHERENT: "n/a"}
REGISTRY_PAGE = "docs/reference/capability-registry.md"
FIELDS_PAGE = "docs/reference/scene-field-consumption.md"
GRADIENT_PAGE = "docs/reference/gradient-capability-matrix.md"
CENSUS_PAGE = "docs/reference/fdtd-capability-guard-census.md"
CENSUS_JSON = "docs/reference/fdtd-capability-guards.json"


def _text(value: str | None) -> str:
    """A reason template as table text: format fields become ``<name>``."""
    if not value:
        return ""
    return re.sub(r"\{(\w+)(?:[^}]*)\}", r"<\1>", value).replace("|", "\\|")


def _table(header: tuple[str, ...], rows) -> str:
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    lines += ["| " + " | ".join(cells) + " |" for cells in rows]
    return "\n".join(lines)


def refusals(methods: tuple[str, ...]) -> str:
    """Every refusal row of ``methods``, one line per row shared by the same methods."""
    grouped: dict[tuple, list[str]] = {}
    for method in methods:
        for key, capability in capabilities(method).items():
            if capability.support is not Support.SUPPORTED:
                identity = (key, capability.support, capability.reason, capability.alternative)
                grouped.setdefault(identity, []).append(method)
    rows = [(f"`{key}`", ", ".join(f"`{method}`" for method in members), LABEL[support], _text(reason),
             _text(alternative))
            for (key, support, reason, alternative), members in sorted(grouped.items(), key=lambda item: item[0][0])]
    return _table(("Feature key", "Method", "Supported", "Refusal", "Alternative"), rows)


def support_matrix() -> str:
    """Every scene feature key that some method refuses, decided per method as the scene check decides it."""
    rows = []
    for key in SCENE_KEYS:
        decided = [row(method, key) for method in METHODS]
        if all(capability.support is Support.SUPPORTED for capability in decided):
            continue
        cells = (LABEL[capability.support] if capability.key == key else
                 f"{LABEL[capability.support]} (`{capability.key}`)" for capability in decided)
        rows.append((f"`{key}`", *cells))
    legend = ("`yes`: admitted at construction (a runtime guard may still refuse a narrower configuration); `no`: "
              "refused, the method could gain it; `n/a`: refused, it has no meaning for the method. A key in "
              "parentheses is the refused collection or prefix that decides the cell.")
    return legend + "\n\n" + _table(("Feature key", *(f"`{method}`" for method in METHODS)), rows)


def trainable_inputs() -> str:
    keys = [key for key in FEATURE_KEYS if "trainable" in key]
    rows = [(f"`{key}`", *(LABEL[row(method, key).support] for method in METHODS)) for key in keys]
    return _table(("Trainable input key", *(f"`{method}`" for method in METHODS)), rows)


def native_adjoint_inventory() -> str:
    from witwin.maxwell.fdtd.adjoint.capabilities import NATIVE_ADJOINT_CAPABILITIES

    rows = [(f"`{name}`", ", ".join(f"`{flag}`" if value is True else f"`{flag}={value}`"
                                    for flag, value in flags.items()))
            for name, flags in NATIVE_ADJOINT_CAPABILITIES.items()]
    return _table(("Inventory entry", "Capability flags"), rows)


def census_registry_rows() -> str:
    census = json.loads((ROOT / CENSUS_JSON).read_text())
    rows = [(f"`{entry['id'].split(':')[0][:8]}…`", f"`{entry['scope']}`",
             ", ".join(f"`{item}`" for item in entry["registry_rows"]))
            for entry in census["retired"] if entry.get("registry_rows")]
    return _table(("Identity prefix", "Former scope", "Registry rows (`method:key`)"), rows)


def registry_page() -> str:
    parts = ["# Capability registry", "", GENERATED, "",
             "One table per method of `witwin/maxwell/capability/tables/`. `Simulation.<method>(scene, ...)` "
             "refuses every feature key whose row is not supported, and any key without a row, in one "
             "`UnsupportedFeatureError`. `mw.capabilities(method)` returns the same table.", ""]
    for method in METHODS:
        table = capabilities(method)
        rows = [(f"`{key}`", LABEL[capability.support], _text(capability.reason), _text(capability.alternative),
                 "<br>".join(f"`{test}`" for test in capability.negative_tests))
                for key, capability in sorted(table.items())]
        parts += [f"## `{method}`", "", _table(("Feature key", "Supported", "Refusal", "Alternative",
                                                "Negative tests"), rows), ""]
    return "\n".join(parts)


def _cell(cell) -> str:
    if cell.support is None:
        return "neutral"
    label = "gap" if cell.gap else LABEL[cell.support] if cell.key or cell.support is Support.SUPPORTED else "not read"
    if cell.key and cell.support is not Support.SUPPORTED:
        label += f" (`{cell.key}`)"
    if cell.conditional and cell.support is Support.SUPPORTED:
        label += "; refuses " + ", ".join(f"`{key}`" for key in cell.conditional)
    return label


def fields_page() -> str:
    parts = ["# Scene field consumption", "", GENERATED, "",
             "How each method treats every public scene field, from `witwin/maxwell/capability/fields.py`. "
             "`yes`: read (or refused by a runtime guard); `no`/`n/a` with a key: refused through that registry "
             "row; `not read`: admitted and deliberately not read (no meaning for the method); `gap`: admitted "
             "and dropped, an open defect pinned by `tests/api/public/test_field_manifest.py`; `neutral`: "
             "identity or bookkeeping. `refuses` lists keys that particular values emit and the method refuses.",
             ""]
    for entry in ENTRIES:
        cells = consumption(entry.cls)
        context = [f"admitted as `{entry.owner}`"] if entry.owner else []
        if entry.within:
            context.append("held by " + ", ".join(f"`{holder}`" for holder in entry.within))
        rows = [(f"`{name}`", *(_cell(cells[name][method]) for method in METHODS)) for name in entry.fields]
        parts += [f"## `{entry.cls.__name__}`", ""]
        if context:
            sentence = "; ".join(context)
            parts += [sentence[0].upper() + sentence[1:] + ".", ""]
        parts += [_table(("Field", *(f"`{method}`" for method in METHODS)), rows), ""]
    reasons = sorted({(entry.cls.__name__, name, method, cell.reason)
                      for entry in ENTRIES for name, by_method in consumption(entry.cls).items()
                      for method, cell in by_method.items()
                      if cell.key is None and cell.support in (Support.INHERENT, Support.UNSUPPORTED)
                      and (method in entry.fields[name].not_read or method in entry.fields[name].gaps)})
    parts += ["## Reasons for fields a method does not read", "",
              _table(("Field", "Method", "Reason"),
                     [(f"`{cls}.{name}`", f"`{method}`", _text(reason)) for cls, name, method, reason in reasons]),
              ""]
    return "\n".join(parts)


BLOCKS = {
    ("FEATURE_LIST.md", "fdfd"): lambda: refusals(("fdfd",)),
    ("FEATURE_LIST.md", "known-limitations"): support_matrix,
    ("FEATURE_LIST.md", "mom"): lambda: refusals(("mom", "mom.layered")),
    ("FEATURE_LIST.md", "electrostatics"): lambda: refusals(("electrostatic", "capacitance")),
    (GRADIENT_PAGE, "trainable-inputs"): trainable_inputs,
    (GRADIENT_PAGE, "native-adjoint-inventory"): native_adjoint_inventory,
    (CENSUS_PAGE, "registry-rows"): census_registry_rows,
}
PAGES = {REGISTRY_PAGE: registry_page, FIELDS_PAGE: fields_page}


def _replace_block(text: str, name: str, body: str, path: str) -> str:
    start, end = f"<!-- capability-table: {name} -->", f"<!-- /capability-table: {name} -->"
    if text.count(start) != 1 or text.count(end) != 1:
        raise ValueError(f"{path} needs exactly one {start} ... {end} block")
    head, rest = text.split(start)
    _, tail = rest.split(end)
    return f"{head}{start}\n{GENERATED}\n\n{body}\n{end}{tail}"


def render() -> dict[str, str]:
    """The expected content of every generated page and of every file with generated blocks."""
    expected = {path: build() + "\n" for path, build in PAGES.items()}
    for (path, name), build in BLOCKS.items():
        text = expected.get(path) or (ROOT / path).read_text()
        expected[path] = _replace_block(text, name, build(), path)
    return expected


def stale(expected: dict[str, str]) -> dict[str, str]:
    """``{path: unified diff}`` for every file whose content differs from ``expected``."""
    diffs = {}
    for path, text in expected.items():
        file = ROOT / path
        current = file.read_text() if file.exists() else ""
        if current != text:
            diffs[path] = "".join(difflib.unified_diff(current.splitlines(True), text.splitlines(True), path, path))
    return diffs


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--write", action="store_true", help="regenerate the tables in place")
    args = parser.parse_args(argv)
    expected = render()
    diffs = stale(expected)
    if args.write:
        for path in diffs:
            (ROOT / path).write_text(expected[path])
        print(f"updated {len(diffs)} file(s)" + "".join(f"\n  {path}" for path in diffs))
        return 0
    for diff in diffs.values():
        sys.stdout.write(diff)
    return 1 if diffs else 0


if __name__ == "__main__":
    raise SystemExit(main())
