"""Generate the JSON Schemas of the versioned payloads into witwin/maxwell/schemas.

    python scripts/dev/scene_schema.py           # check: exit 1 when a committed file is stale
    python scripts/dev/scene_schema.py --write   # regenerate the schemas and VERSIONS.toml

Policy (witwin.maxwell.io.schema): an additive change bumps the payload's revision; a breaking change
is refused until the payload's version constant is bumped and witwin.maxwell.io.schema.MIGRATIONS has a
migrator for the previous version. tests/api/public/test_schema_versions.py fails on unrecorded changes.
"""
from __future__ import annotations

import argparse
import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from witwin.maxwell.io.schema import versions_table  # noqa: E402

DIRECTORY = ROOT / "witwin/maxwell/schemas"
HEADER = """# Versioned payloads of witwin-maxwell: version, revision and sha256 of the generated JSON Schema.
# Generated by scripts/dev/scene_schema.py --write; checked by tests/api/public/test_schema_versions.py.
# An additive schema change bumps the revision; a breaking one needs a new version and a migrator.
# A payload without a generated schema (schema = "") is checked by its version only.
"""


def committed_schema(file: str):
    path = DIRECTORY / file
    return json.loads(path.read_text()) if path.exists() else None


def versions_text(table: dict) -> str:
    return HEADER + "".join(
        f'\n["{name}"]\nversion = "{entry["version"]}"\nrevision = {entry["revision"]}\n'
        f'schema = "{entry["schema"]}"\nsha256 = "{entry["sha256"]}"\n' for name, entry in table.items())


def generated() -> tuple[dict[str, str], list[str]]:
    """File name -> text of every generated file (the schemas and VERSIONS.toml), and blocking problems."""
    path = DIRECTORY / "VERSIONS.toml"
    recorded = tomllib.loads(path.read_text()) if path.exists() else {}
    table, files, problems = versions_table(recorded, committed_schema)
    return {**files, "VERSIONS.toml": versions_text(table)}, problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    files, problems = generated()
    if problems:
        print("refused:\n  " + "\n  ".join(problems))
        return 1
    stale = [file for file, text in files.items()
             if not (DIRECTORY / file).exists() or (DIRECTORY / file).read_text() != text]
    if args.write:
        for file in stale:
            (DIRECTORY / file).write_text(files[file])
        print("wrote", ", ".join(stale) or "nothing (current)")
        return 0
    if stale:
        print("stale:", ", ".join(stale), "- run python scripts/dev/scene_schema.py --write")
        return 1
    print("current", DIRECTORY)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
